// ------------------------------------------------------------------ badges

export function Badge({ tone = "neutral", children }: { tone?: "neutral" | "good" | "bad" | "accent" | "warn"; children: ReactNode }) {
  return <span className={`badge ${tone}`}>{children}</span>;
}

export function VerdictBadge({ verdict }: { verdict: Verdict }) {
  if (verdict === "improved") return <Badge tone="good">▲ improved</Badge>;
  if (verdict === "regressed") return <Badge tone="bad">▼ regressed</Badge>;
  if (verdict === "insufficient data") return <Badge tone="warn">? insufficient data</Badge>;
  return <Badge>● no significant change</Badge>;
}

export function CICell({ ci, digits = 3 }: { ci: CI | null | undefined; digits?: number }) {
  if (!ci) return <span className="ci">n/a</span>;
  return (
    <>
      {num(ci.estimate, digits)}{" "}
      <span className="ci">
        [{num(ci.low, 2)}, {num(ci.high, 2)}]
      </span>
    </>
  );
}

// ------------------------------------------------------------------ controls

export function Tabs<T extends string>({
  items,
  value,
  onChange,
}: {
  items: { id: T; label: string }[];
  value: T;
  onChange: (v: T) => void;
}) {
  return (
    <div className="tabs" role="tablist">
      {items.map((it) => (
        <button
          key={it.id}
          role="tab"
          aria-selected={value === it.id}
          className={`tab ${value === it.id ? "active" : ""}`}
          onClick={() => onChange(it.id)}
        >
          {it.label}
        </button>
      ))}
    </div>
  );
}

export function Segmented<T extends string>({
  items,
  value,
  onChange,
}: {
  items: { id: T; label: string }[];
  value: T;
  onChange: (v: T) => void;
}) {
  return (
    <div className="seg" role="radiogroup">
      {items.map((it) => (
        <button key={it.id} role="radio" aria-checked={value === it.id} className={value === it.id ? "on" : ""} onClick={() => onChange(it.id)}>
          {it.label}
        </button>
      ))}
    </div>
  );
}

export function Loading({ what }: { what: string }) {
  return <div className="empty">Loading {what}…</div>;
}

export function ErrorBox({ error }: { error: string }) {
  return (
    <div className="card">
      <p className="error">Could not load data: {error}</p>
    </div>
  );
}
