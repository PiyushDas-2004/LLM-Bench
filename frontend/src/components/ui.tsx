import { createContext, useCallback, useContext, useMemo, useState, type ReactNode } from "react";
import type { CI, Verdict } from "../types";
import { num } from "../format";

// ------------------------------------------------------------------ tooltip

interface TipState {
  x: number;
  y: number;
  content: ReactNode;
}

interface TipApi {
  show: (e: { clientX: number; clientY: number }, content: ReactNode) => void;
  hide: () => void;
}

const TipContext = createContext<TipApi>({ show: () => undefined, hide: () => undefined });

export function TooltipProvider({ children }: { children: ReactNode }) {
  const [tip, setTip] = useState<TipState | null>(null);
  const show = useCallback<TipApi["show"]>((e, content) => setTip({ x: e.clientX, y: e.clientY, content }), []);
  const hide = useCallback(() => setTip(null), []);
  const api = useMemo(() => ({ show, hide }), [show, hide]);
  const left = tip ? Math.min(tip.x + 14, window.innerWidth - 330) : 0;
  return (
    <TipContext.Provider value={api}>
      {children}
      {tip && (
        <div className="tooltip" style={{ left, top: tip.y + 14 }} role="tooltip">
          {tip.content}
        </div>
      )}
    </TipContext.Provider>
  );
}

export const useTooltip = (): TipApi => useContext(TipContext);

// ------------------------------------------------------------------ layout

export function Card({
  title,
  sub,
  actions,
  children,
}: {
  title?: ReactNode;
  sub?: ReactNode;
  actions?: ReactNode;
  children: ReactNode;
}) {
  return (
    <section className="card">
      {(title || actions) && (
        <div className="card-head">
          <div>
            {title && <h2>{title}</h2>}
            {sub && <div className="card-sub">{sub}</div>}
          </div>
          {actions}
        </div>
      )}
      {children}
    </section>
  );
}

export function Stat({ k, v, s }: { k: string; v: ReactNode; s?: ReactNode }) {
  return (
    <div className="card stat">
      <div className="k">{k}</div>
      <div className="v">{v}</div>
      {s && <div className="s">{s}</div>}
    </div>
  );
}

export function PageHead({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <header className="page-head">
      <h1>{title}</h1>
      {children && <p>{children}</p>}
    </header>
  );
}

